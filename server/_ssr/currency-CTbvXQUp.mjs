/**
* Rates are USD -> currency. EUR is a reference rate only, since this app
* has no live FX feed.
*/
var CURRENCIES = [{
	code: "USD",
	label: "US Dollar",
	symbol: "$",
	rate: 1,
	pegged: true
}, {
	code: "EUR",
	label: "Euro",
	symbol: "€",
	rate: .92
}];
function convertFromUsd(amountUsd, currency) {
	return amountUsd * (CURRENCIES.find((c) => c.code === currency)?.rate ?? 1);
}
function formatCurrency(amountUsd, currency, locale = "en-US") {
	const converted = convertFromUsd(amountUsd, currency);
	try {
		return new Intl.NumberFormat(locale, {
			style: "currency",
			currency
		}).format(converted);
	} catch {
		return `${CURRENCIES.find((c) => c.code === currency)?.symbol ?? "$"}${converted.toLocaleString()}`;
	}
}
